"""The invariants of note 03 and of Volume 7 of the handbook.

For a clean F with the divisor E, write F = x^r G with r over E as large as possible. Then:

- d = ord G is the residual order.
- Theta-tilde(G) is the ideal generated by r_i G + x_i dG/dx_i for i in E and dG/dx_j for j not in E. It is Theta(F) divided by x^r.
- rho is the residual order of Theta(F): the order of Theta-tilde(G) minus the degree of its monomial factor over E. For a clean F, rho is d - 1 or d (Theorem 3.7 of note 03), and tau = d - rho is the type.
- nu^G along a coordinate stratum V(x_i, i in S) is the order of F along it minus the sum of the r_i for i in S and E (Lemma 3.13.1 of the handbook).
"""

from dataclasses import dataclass

from .charts import clean


@dataclass(frozen=True)
class Residual:
    r: tuple
    G: object
    d: int


def residual(F, E):
    """The monomial factor r over E, the residual factor G and the residual order d."""
    E = F.ring.indices(E)
    r = F.monomial_factor(E)
    G = F.divide_monomial(r)
    return Residual(r, G, G.order())


def theta(F, E):
    """The generators of Theta(F): x_i dF/dx_i for i in E and dF/dx_j for j not in E."""
    E = F.ring.indices(E)
    return [F.log_deriv(i) if i in E else F.deriv(i) for i in range(F.ring.n)]


def theta_tilde(F, E):
    """The generators of Theta-tilde(G): r_i G + x_i dG/dx_i for i in E, dG/dx_j for j not in E."""
    E = F.ring.indices(E)
    res = residual(F, E)
    G, K = res.G, F.ring.F
    out = []
    for i in range(F.ring.n):
        if i in E:
            out.append(G.scale(K.from_int(res.r[i])) + G.log_deriv(i))
        else:
            out.append(G.deriv(i))
    return out


def theta_tilde_centre(F, E, S):
    """The generators of Theta-tilde_C(G) for the centre C = V(x_i, i in S): r_i G + x_i dG/dx_i for i in E, dG/dx_j for j not in E and not in S, and x_k dG/dx_j for j in S and not in E, k in S."""
    R = F.ring
    E, S = R.indices(E), R.indices(S)
    res = residual(F, E)
    G, K = res.G, R.F
    out = []
    for i in range(R.n):
        if i in E:
            out.append(G.scale(K.from_int(res.r[i])) + G.log_deriv(i))
        elif i not in S:
            out.append(G.deriv(i))
        else:
            dG = G.deriv(i)
            out.extend(R.var(k) * dG for k in sorted(S))
    return out


def ideal_order(gens):
    """The order at the origin of the ideal. None for the zero ideal."""
    orders = [g.order() for g in gens if g]
    return min(orders) if orders else None


def ideal_order_along(gens, S):
    orders = [g.order_along(S) for g in gens if g]
    return min(orders) if orders else None


def ideal_monomial_factor(gens, E):
    """The largest monomial over E that divides each generator."""
    gens = [g for g in gens if g]
    if not gens:
        return None
    n = gens[0].ring.n
    E = gens[0].ring.indices(E)
    return tuple(min(e[i] for g in gens for e in g.terms) if i in E else 0 for i in range(n))


def rho(F, E):
    """The residual order of Theta(F). F must be clean. None if Theta(F) is zero."""
    E = F.ring.indices(E)
    gens = theta_tilde(F, E)
    o = ideal_order(gens)
    if o is None:
        return None
    return o - sum(ideal_monomial_factor(gens, E))


@dataclass(frozen=True)
class Invariants:
    r: tuple
    d: int
    rho: int
    tau: int
    terms: int


def invariants(F, E, q=None):
    """r, d, rho and tau of F with the divisor E. With q, F is cleaned first."""
    if q is not None:
        F, _ = clean(F, q)
    res = residual(F, E)
    rh = rho(F, E)
    tau = None if rh is None or res.d is None else res.d - rh
    return Invariants(res.r, res.d, rh, tau, len(F))


@dataclass(frozen=True)
class Hypotheses:
    rho: int
    ord_C_theta: int
    ord_C_theta_C: int
    ord_0_theta_C: int

    @property
    def h1(self):
        """(H1): ord_C Theta-tilde = rho."""
        return self.ord_C_theta == self.rho

    @property
    def h2(self):
        """(H2): ord_C Theta-tilde_C = rho + 1, or ord_0 Theta-tilde_C = rho."""
        return self.ord_C_theta_C == self.rho + 1 or self.ord_0_theta_C == self.rho


def hypotheses(F, E, S):
    """The data of (H1) and (H2) of Theorem 3.16 of note 03 for the centre V(x_i, i in S)."""
    R = F.ring
    E, S = R.indices(E), R.indices(S)
    tt = theta_tilde(F, E)
    tc = theta_tilde_centre(F, E, S)
    return Hypotheses(rho(F, E), ideal_order_along(tt, S), ideal_order_along(tc, S), ideal_order(tc))


def nu_G(F, E, S):
    """nu^G along the coordinate stratum V(x_i, i in S), for F clean in these coordinates (Lemma 3.13.1 of the handbook)."""
    R = F.ring
    E, S = R.indices(E), R.indices(S)
    r = F.monomial_factor(E)
    return F.order_along(S) - sum(r[i] for i in S & E)


def is_monomial_times_unit(f, E):
    """True if f is a monomial in the variables of E times a unit."""
    if not f:
        return False
    s = f.monomial_factor(E)
    return f.divide_monomial(s).value_at_origin() != 0


def free_coordinate(F, x, w, lam, gamma=None):
    """Write F in a new free coordinate system and clean it with q = p.

    For lam in the field, the new coordinates are X = x + lam w + gamma and W = w. For lam = None, they are X = w + gamma and W = x. gamma is a polynomial in the variables other than x and w, or None. The result uses the old names, with X in the place of x and W in the place of w.
    """
    R = F.ring
    x, w = R.index(x), R.index(w)
    K = R.F
    gam = gamma if gamma is not None else R.zero()
    if lam is None:
        # w = X - gamma, x = W.
        images = {x: R.var(w), w: R.var(x) - gam}
    else:
        images = {x: R.var(x) - R.var(w).scale(lam) - gam}
    G = F.substitute(images)
    G, _ = clean(G, K.p)
    return G


def lines(K):
    """The free lines X = x + lam w for lam in K, and X = w (lam = None)."""
    return list(K.elements()) + [None]
